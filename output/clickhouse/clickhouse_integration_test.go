// Point ADDER_TEST_CLICKHOUSE_URL at a dedicated test database for a live
// JSONEachRow, DateTime64, rollback, and duplicate-retention check.
func TestClickHouseIntegration(t *testing.T) {
	endpoint := os.Getenv("ADDER_TEST_CLICKHOUSE_URL")
	if endpoint == "" {
		t.Skip("set ADDER_TEST_CLICKHOUSE_URL for ClickHouse integration")
	}
	database := os.Getenv("ADDER_TEST_CLICKHOUSE_DATABASE")
	require.NotEmpty(t, database, "set ADDER_TEST_CLICKHOUSE_DATABASE to a dedicated test database")
	require.NotEqual(t, "default", database, "use a dedicated test database, not default")
	o := New(WithURL(endpoint), WithDatabase(database), WithUsername(os.Getenv("ADDER_TEST_CLICKHOUSE_USER")), WithPassword(os.Getenv("ADDER_TEST_CLICKHOUSE_PASSWORD")))
	if o.username == "" {
		o.username = "default"
	}
	require.NoError(t, o.validate())
	o.client = &http.Client{Timeout: requestTimeout}
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	require.NoError(t, o.query(ctx, createSQL, nil, false))
	stamp := time.Now().UTC()
	block := event.New(event.TypeBlock, stamp, nil, map[string]any{"integration_nonce": stamp.UnixNano()})
	rollback := event.New(event.TypeRollback, stamp, nil, map[string]any{"slot": 42})
	blockRow, err := encodeRow(block)
	require.NoError(t, err)
	rollbackRow, err := encodeRow(rollback)
	require.NoError(t, err)
	for _, row := range [][]byte{blockRow, rollbackRow, blockRow} {
		require.NoError(t, o.query(ctx, insertSQL, append(bytes.Clone(row), '\n'), true))
	}
	// event_hash is a hex string generated by encodeRow. The dedicated test DB
	// prevents other writers from interfering with this exact count.
	var row struct {
		EventHash string `json:"event_hash"`
	}
	require.NoError(t, json.Unmarshal(blockRow, &row))
	query := url.Values{"query": {fmt.Sprintf("SELECT count() FROM adder_events_v1 WHERE event_hash = '%s' FORMAT TabSeparated", row.EventHash)}}
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, strings.TrimSuffix(endpoint, "/")+"/?"+query.Encode(), nil)
	require.NoError(t, err)
	req.Header.Set("X-ClickHouse-User", o.username)
	req.Header.Set("X-ClickHouse-Database", o.database)
	if o.password != "" {
		req.Header.Set("X-ClickHouse-Key", o.password)
	}
	client := *o.client
	client.CheckRedirect = func(*http.Request, []*http.Request) error { return http.ErrUseLastResponse }
	resp, err := client.Do(req)
	require.NoError(t, err)
	defer resp.Body.Close()
	data, err := io.ReadAll(io.LimitReader(resp.Body, 1024))
	require.NoError(t, err)
	require.Equal(t, http.StatusOK, resp.StatusCode, string(data))
	count, err := strconv.Atoi(strings.TrimSpace(string(data)))
	require.NoError(t, err)
	require.Equal(t, 2, count)
}
